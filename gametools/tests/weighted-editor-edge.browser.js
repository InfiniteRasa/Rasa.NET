async (page) => {
  const failures = [], check = (ok, text) => { if (!ok) failures.push(text); };
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('tab',{name:'Profiles and groups',exact:true}).click();
  await page.locator('#g-key').fill('gear_renamed');
  await page.locator('#g-key').dispatchEvent('change');
  check(await page.locator('#g-select option[value="gear_renamed"]').count() === 1, 'Renaming a group updates the selected group control.');
  await page.locator('#p-key').fill('test_renamed');
  await page.locator('#p-key').dispatchEvent('change');
  check(await page.locator('#p-list [data-profile="test_renamed"]').count() === 1, 'Renaming a profile updates the profile list and binding choices.');
  if (failures.length) return {red:failures};
  await page.locator('#p-provenance').fill('<script>not markup</script> 中文 العربية ' + 'long '.repeat(80));
  await page.locator('#p-provenance').dispatchEvent('change');
  await page.getByRole('tab',{name:'Save and export',exact:true}).click();
  await page.evaluate(() => {
    const click=HTMLAnchorElement.prototype.click;
    HTMLAnchorElement.prototype.click=function() { window.exportName=this.download; };
    window.restoreDownload=() => { HTMLAnchorElement.prototype.click=click; };
    const create=URL.createObjectURL;
    URL.createObjectURL=function(blob) { window.exportBlob=blob; return create(blob); };
  });
  await page.getByRole('button',{name:'Save project file',exact:true}).click();
  const exported=await page.evaluate(async()=>JSON.parse(await window.exportBlob.text()));
  check(exported.profiles[0].profileKey==='test_renamed' && exported.items[0].groupKey==='gear_renamed', 'Local file export uses canonical renamed keys.');
  check(exported.bindings.every(r=>r.profileKey==='test_renamed'), 'Profile renaming updates existing binding references.');
  check(exported.profiles[0].provenance.includes('<script>') && !('apiKey' in exported), 'Unicode metadata is kept as data; no config keys are exported.');
  exported.items[0].itemTemplateId=4294967295;
  await page.locator('#x-file').setInputFiles({name:'weighted.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
  await page.waitForFunction(()=>document.getElementById('x-msg').textContent.startsWith('Loaded weighted'));
  await page.getByRole('tab',{name:'Profiles and groups',exact:true}).click();
  check(await page.locator('#i-body').textContent().then(s=>s.includes('4294967295')), 'Unknown native IDs are retained for server validation, never discarded.');
  await page.locator('input[data-field="weight"]').first().fill('0');
  await page.locator('input[data-field="weight"]').first().dispatchEvent('change');
  await page.getByRole('tab',{name:'Save and export',exact:true}).click();
  check(await page.getByRole('button',{name:'Send to server',exact:true}).isDisabled(), 'Invalid weight disables remote save.');
  check(await page.locator('#x-checks').textContent().then(s=>s.includes('weight')), 'Invalid weight has an actionable check.');
  check(await page.locator('#sql').inputValue()==='', 'Invalid draft has no executable SQL export.');
  await page.getByRole('tab',{name:'Profiles and groups',exact:true}).click();
  check(await page.locator('input[data-field="weight"]').first().inputValue()==='0', 'Invalid input is not silently normalized.');
  await page.locator('input[data-field="weight"]').first().fill('3');
  await page.locator('input[data-field="weight"]').first().dispatchEvent('change');
  await page.locator('#tab-profiles').focus(); await page.keyboard.press('End');
  check(await page.locator('#tab-export').getAttribute('aria-selected')==='true', 'Tabs support keyboard End.');
  await page.keyboard.press('ArrowLeft');
  check(await page.locator('#tab-bindings').getAttribute('aria-selected')==='true', 'Tabs support arrow navigation.');
  await page.locator('#policy-map').fill('10');
  await page.locator('#policy-required').uncheck();
  await page.getByRole('button',{name:'Set map policy',exact:true}).click();
  check(await page.locator('#binding-msg').textContent().then(s=>s.includes('cannot be disabled')), 'Required map policies cannot be weakened.');
  await page.evaluate(()=>window.restoreDownload());
  return {passed:failures.length===0,failures,exportedFormat:exported.format};
}
