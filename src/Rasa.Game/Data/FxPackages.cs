        /// <summary>The package's string table id, by name, whatever its case, with or without ".pkg".</summary>
        public static bool TryResolve(string text, out uint id)
        {
            id = 0;

            if (string.IsNullOrWhiteSpace(text))
                return false;

            if (uint.TryParse(text, out id))
                return Names.ContainsKey(id);

            var name = text.EndsWith(".pkg", StringComparison.OrdinalIgnoreCase) ? text[..^4] : text;

            return ByName.TryGetValue(name, out id);
        }

        /// <summary>The package's name, or "#id" for one the client does not have.</summary>
        public static string NameOf(uint id) => Names.TryGetValue(id, out var name) ? name : $"#{id}";

        /// <summary>Packages whose name contains every one of the words, by name.</summary>
        public static List<(uint Id, string Name)> Search(IEnumerable<string> words)
        {
            var wanted = words.Where(w => !string.IsNullOrWhiteSpace(w)).Select(w => w.ToLowerInvariant()).ToList();

            return Names.Where(p => wanted.All(w => p.Value.ToLowerInvariant().Contains(w)))
                .OrderBy(p => p.Value, StringComparer.Ordinal)
                .Select(p => (p.Key, p.Value))
                .ToList();
        }

