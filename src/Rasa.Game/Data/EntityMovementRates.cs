        public static (float Walk, float Run) Resolve(uint classId, float walk, float run)
        {
            if (!TryGet(classId, out var classWalk, out var classRun))
                return (walk, run);

            return (walk == PlaceholderWalk ? classWalk : walk, run == PlaceholderRun ? classRun : run);
        }

        /// <summary>Puts the creature on its class's rates where it carries the placeholders (<see cref="Resolve"/>).</summary>
        public static void Apply(Creature creature)
        {
            if (creature == null)
                return;

            (creature.WalkSpeed, creature.RunSpeed) = Resolve((uint)creature.EntityClass, creature.WalkSpeed, creature.RunSpeed);
        }
    }
