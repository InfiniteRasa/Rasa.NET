    /// <summary>
    /// One keyframe of a camera script: where the camera is, how it is turned (a quaternion, w
    /// first, as the .map stores it), its focal length, how long it takes to get there from the
    /// keyframe before and how long it holds there.
    /// </summary>
    public sealed class CameraKeyframe
    {
        public CameraKeyframe(float x, float y, float z, float w, float qx, float qy, float qz, float focalLength, int arriveMs, int holdMs)
        {
            Position = new Vector3(x, y, z);
            Orientation = new Quaternion(qx, qy, qz, w);
            FocalLength = focalLength;
            ArriveMs = arriveMs;
            HoldMs = holdMs;
        }

        public Vector3 Position { get; }
        public Quaternion Orientation { get; }
        public float FocalLength { get; }
        public int ArriveMs { get; }
        public int HoldMs { get; }

        /// <summary>
        /// Which way the camera looks: its local +z turned by its orientation. Read off the data,
        /// not the client's code: with +z, 450 of the 502 keyframes look down a little (half of
        /// them by 11 degrees or more), as cameras over a scene do; with -z, as many would look up.
        /// </summary>
        public Vector3 Forward => Vector3.Transform(Vector3.UnitZ, Orientation);

        /// <summary>
        /// The rotation a player or creature has when facing the way the camera looks, level: a
        /// facing r looks along (-sin r, -cos r), the way the server turns models. 0 to 2 pi.
        /// </summary>
        public double Facing
        {
            get
            {
                var forward = Forward;
                var facing = Math.Atan2(-forward.X, -forward.Z);
                return facing < 0 ? facing + 2 * Math.PI : facing;
            }
        }
    }

    /// <summary>A camera script a map carries: its map, its id there, its keyframes and how long it runs.</summary>
    public sealed class CameraScriptInfo
    {
        public CameraScriptInfo(string mapName, uint scriptId, int returnMs, params CameraKeyframe[] frames)
        {
            MapName = mapName;
            ScriptId = scriptId;
            ReturnMs = returnMs;
            Frames = frames;
        }

        public string MapName { get; }
        public uint ScriptId { get; }

        /// <summary>How long the camera takes to come back to the player after the last keyframe.</summary>
        public int ReturnMs { get; }
        public IReadOnlyList<CameraKeyframe> Frames { get; }
        public int Keyframes => Frames.Count;

        /// <summary>Every keyframe's arrive and hold time and the script's return time, added up.</summary>
        public long LengthMs => Frames.Sum(frame => (long)frame.ArriveMs + frame.HoldMs) + ReturnMs;

        public CameraKeyframe First => Frames[0];
        public CameraKeyframe Last => Frames[Frames.Count - 1];

        /// <summary>How far the camera is from a point at its nearest keyframe.</summary>
        public float DistanceTo(Vector3 point) => Frames.Min(frame => Vector3.Distance(frame.Position, point));
    }

